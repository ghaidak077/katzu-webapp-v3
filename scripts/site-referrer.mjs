/**
 * Which AI assistant sent this reader — one list, two hosts.
 *
 * WHY IT EXISTS
 * The site and the app are two origins, and AI answers cite both. A guide on
 * `website.katzuai.com` is the likely landing for a ChatGPT or Perplexity answer;
 * a bare `katzuai.com` link lands on the app shell. Without a referrer bucket,
 * every one of those visits looks like "direct" and the effect of publishing
 * twelve guides is unmeasurable.
 *
 * WHAT IS RECORDED
 * One word: `chatgpt`, `perplexity`, `gemini`, `copilot` or `claude`. It travels
 * on the existing `landing_viewed` event as its existing allowlisted `source`
 * property, so no event name, property key or worker contract changes. The full
 * URL is never sent, and an unknown referrer is dropped rather than stored.
 *
 * WHAT IS NOT
 * No cookie, no storage, no identifier that follows a reader from one page to
 * the next. The site script mints a random id per page view that dies with the
 * tab; the app reuses the anonymous installation id it already has.
 *
 * A test pins this list to the app's copy in `src/lib/analytics/referrer.ts`, the
 * same way `PROP_KEYS` is pinned to its client twin.
 */

export const AI_REFERRERS = [
  // `chat.openai.com` is the legacy host; links still arrive from it.
  { source: 'chatgpt', hosts: ['chatgpt.com', 'chat.openai.com'] },
  { source: 'perplexity', hosts: ['perplexity.ai'] },
  { source: 'gemini', hosts: ['gemini.google.com'] },
  { source: 'copilot', hosts: ['copilot.microsoft.com'] },
  { source: 'claude', hosts: ['claude.ai'] },
];

/**
 * The source for a referrer, or null. A lookalike host (`chatgpt.com.evil.test`,
 * `notchatgpt.com`) must never match, so the test is equality or a dot boundary
 * — never `includes`.
 */
export function aiReferrerSource(referrer) {
  let host = '';
  try {
    host = new URL(String(referrer || '')).hostname.toLowerCase().replace(/^www\./, '');
  } catch {
    return null;
  }
  if (!host) return null;
  for (const { source, hosts } of AI_REFERRERS) {
    for (const candidate of hosts) {
      if (host === candidate || host.endsWith(`.${candidate}`)) return source;
    }
  }
  return null;
}

/**
 * `/assets/ai-ref.js` — the same rule, in the browser, on the marketing site.
 *
 * The site has no analytics client and no installation id, and it is not going
 * to grow one for a referral count. So the id is generated in memory for the one
 * request and discarded: the worker's allowlist needs a well-formed id, not a
 * durable one. `keepalive` lets the request finish if the reader clicks away
 * mid-load; `credentials: "omit"` keeps it cookieless.
 */
export function aiReferrerScript(worker) {
  return `/* Generated by scripts/build-website.mjs. Do not edit. */
(function () {
  var REFERRERS = ${JSON.stringify(AI_REFERRERS)};
  var host = "";
  try {
    host = new URL(document.referrer).hostname.toLowerCase().replace(/^www\\./, "");
  } catch (e) {
    return;
  }
  if (!host) return;

  var source = "";
  for (var i = 0; i < REFERRERS.length && !source; i++) {
    var hosts = REFERRERS[i].hosts;
    for (var j = 0; j < hosts.length; j++) {
      var h = hosts[j];
      if (host === h || host.slice(-(h.length + 1)) === "." + h) {
        source = REFERRERS[i].source;
        break;
      }
    }
  }
  if (!source) return;

  // Random, in memory, thrown away: no cookie and no storage, so this cannot
  // follow a reader to another page.
  var id = "site_" + Math.random().toString(36).slice(2) + Date.now().toString(36);

  try {
    fetch(${JSON.stringify(worker)} + "/analytics/events", {
      method: "POST",
      headers: { "Content-Type": "application/json;charset=UTF-8" },
      body: JSON.stringify({
        events: [
          {
            name: "landing_viewed",
            ts: Date.now(),
            installId: id,
            appVersion: "site",
            route: location.pathname,
            props: { source: source },
          },
        ],
      }),
      credentials: "omit",
      keepalive: true,
    }).catch(function () {});
  } catch (e) {
    /* an unreachable worker must never break a page */
  }
})();
`;
}

/** The tag itself, next to the partner-link reader. */
export const AI_REF_SCRIPT = '<script src="/assets/ai-ref.js" defer></script>';
