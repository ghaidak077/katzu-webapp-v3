/**
 * The crawlers both hosts must let in, and the private paths they may not read.
 *
 * WHY A SHARED LIST
 * `website.katzuai.com` and `katzuai.com` are two deployments with two robots
 * files, and a list that disagrees between them is a fact with two answers.
 * Both build steps import this module, so adding a crawler is one line in one
 * file and a rebuild of both.
 *
 * WHY NAME THEM AT ALL
 * `User-agent: *` already allows every one of them. Naming them is evidence: a
 * Cloudflare bot rule, a WAF block or a challenge page can still answer 403 to a
 * named crawler, and a robots file that speaks to it directly is what an owner
 * (or a support ticket) can point at. The list is also the crawl panel in
 * `docs/agent/OWNER-CHECKLIST.md`, checked agent by agent.
 */

/** Search engines and AI crawlers that must receive the public pages. */
export const CRAWLER_AGENTS = [
  'Googlebot',
  'bingbot',
  'GPTBot',
  'OAI-SearchBot',
  'ChatGPT-User',
  'ClaudeBot',
  'Claude-SearchBot',
  'PerplexityBot',
  'Applebot',
  'Google-Extended',
];

/**
 * Private surfaces, on both hosts. Nothing here serves a public page: `/admin/`
 * is the control plane, `/api/` the worker proxy, `/private/` a reserved name.
 */
export const PRIVATE_PATHS = ['/admin/', '/api/', '/private/'];

/**
 * One robots.txt. Named crawlers first, then the wildcard group with the same
 * rules, then the sitemap. `Allow: /` is stated before each `Disallow` because a
 * longer path wins in the standard, and stating it keeps the intent readable.
 */
export function robotsTxt(sitemapUrl) {
  const group = (agent) =>
    [`User-agent: ${agent}`, 'Allow: /', ...PRIVATE_PATHS.map((path) => `Disallow: ${path}`)].join('\n');

  return [
    '# Search engines and AI crawlers are welcome to every public page.',
    '# The private surfaces are not public and are named below.',
    '# Generated by the build from scripts/seo-agents.mjs.',
    '',
    ...CRAWLER_AGENTS.map((agent) => `${group(agent)}\n`),
    group('*'),
    '',
    `Sitemap: ${sitemapUrl}`,
    '',
  ].join('\n');
}
