#!/usr/bin/env node
/**
 * The size budget of every document under `docs/`, in one command.
 *
 * WHY THIS EXISTS
 * The budgets live in `tests/agentDocs.test.ts`, which answers "is anything over?" only as a red
 * gate — after the writing is done. Twice a run pushed a document to the cap and discovered it by
 * running the full suite (the owner checklist on 2026-11-19 had 6 chars of headroom left). The
 * numbers moved here so both readers share one source: the test asserts against it, and
 * `npm run docs:budget` prints the headroom *before* the edit.
 *
 * WHEN A BUDGET IS HIT, THE FIX IS SPLITTING, NOT RAISING
 * Moving history into a focused document (and linking it) keeps the entry point small; raising a
 * number is the same failure one release later. A new cap belongs in this file in the same commit
 * as its reason.
 */
import { readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

export const BUDGETS_KB = {
  'AGENTS.md': 22, // the rules; readable in full, deliberately
  'CLAUDE.md': 4, // a pointer, not a second copy of the rules
  'docs/agent/MEMORY.md': 45, // the digest a run reads in full
  'docs/agent/ENV-FACTS.md': 30, // environment facts; a run reads the sections it needs
  'docs/agent/LESSONS.md': 60, // append-only log; grep it, never load it
  'docs/agent/APP-MAP.md': 135, // the map: read by section, and the cap freezes its growth
  'docs/agent/PROJECT-BRIEF.md': 80, // refreshed per run, read by humans and advisors
  // Live board + current state only. History goes to the archive: `npm run ledger:archive`.
  'docs/AGENT-STATE.md': 80,
  // Named because they sit above DEFAULT_DOC_KB; their caps are the size they measured when this
  // list was written, so the next growth is a decision in a commit instead of drift.
  'docs/PRODUCT-SPEC.md': 105,
  'docs/marketing/KATZU-LAUNCH-PLAYBOOK.md': 85,
  'docs/LEARNING-ROADMAP.md': 42,
  'docs/agent/EXPERIENCE-AUDIT-V31.md': 28,
  'docs/LAUNCH-CHECKLIST.md': 27,
  'docs/agent/LAUNCH-STATUS.md': 25,
  'docs/current-state.md': 24,
  // The admin inspection report is read by the owner and by whoever changes the panel, not
  // loaded at session start; its content-parity and internal-API tables are the reference for
  // both panels, so it is named here rather than split across files.
  'docs/ADMIN.md': 30,
  // Owner-requested product documents (2026-10-16), not agent orientation docs:
  // `katzu-baseline.md` is the row-by-row comparison file the owner asked for and carries the
  // per-task "## Launch tracker" appended during the launch pass, so it must be free to grow;
  // `katzu-user-journey.md` is its companion journey audit.
  'docs/katzu-baseline.md': 120,
  'docs/katzu-user-journey.md': 60,
  // GENERATED by `node scripts/build-language-data.mjs --list`: the German/Arabic pair of all
  // shipped openers, so the owner can proofread them in one pass. Read end to end by the owner,
  // never loaded by a run.
  'docs/OWNER-LANGUAGE-REVIEW.md': 80,
  // GENERATED by the V47 review pass: every Arabic first-message gloss, grouped by level, with
  // the flagged rows and suggested wording. Read end to end by the owner, never loaded by a run.
  'docs/OWNER-OPENER-REVIEW.md': 80,
};

/**
 * The cap every other document gets, without anyone having to name it.
 *
 * WHY A DEFAULT AND NOT JUST THIS MAP
 * When this file first shipped, eight files had budgets and 37 did not — so the next agent could
 * create a 300 KB orientation guide and nothing objected. 22 KB is roughly what a run can read in
 * one go, and every file above it is named above.
 */
export const DEFAULT_DOC_KB = 22;

/**
 * Exempt, with the reason. These documents are searched, never read: `grep -rn "<topic>" docs/`.
 */
export const DOC_EXEMPT = {
  'docs/agent/ARCHIVE-AGENT-STATE.md':
    'append-only history moved out of the ledger; never read whole, only grepped — capping it would mean deleting history, which this repo does not do',
  'docs/agent/APP-MAP-ARCHIVE.md':
    "the older half of APP-MAP's change log, moved verbatim when the map reached its 135 KB budget; append-only history, grepped, never read whole",
};

/** Every markdown file under `docs/`, repo-relative. Empty means the walk broke, not that all is well. */
export const docFiles = (root) => {
  const walk = (dir) =>
    readdirSync(join(root, dir), { withFileTypes: true }).flatMap((entry) =>
      entry.isDirectory() ? walk(`${dir}/${entry.name}`) : [`${dir}/${entry.name}`],
    );
  return walk('docs')
    .filter((file) => file.endsWith('.md'))
    .sort();
};

/**
 * One row per document: measured size, its cap, and what is left.
 * `headroomKb` is negative when the document is over — that is the number to act on.
 */
export const docReport = (root) =>
  docFiles(root).map((file) => {
    const bytes = statSync(join(root, file)).size;
    const exempt = DOC_EXEMPT[file];
    const cap = BUDGETS_KB[file] ?? DEFAULT_DOC_KB;
    const kb = bytes / 1024;
    return {
      file,
      bytes,
      kb: Number(kb.toFixed(2)),
      capKb: exempt ? null : cap,
      named: file in BUDGETS_KB,
      exempt: Boolean(exempt),
      over: !exempt && kb > cap,
      headroomKb: exempt ? null : Number((cap - kb).toFixed(2)),
    };
  });

const main = () => {
  const root = join(process.cwd());
  const rows = docReport(root);
  if (!rows.length) {
    console.error('the docs walk found nothing — wrong directory?');
    process.exit(2);
  }
  const live = rows.filter((row) => !row.exempt);
  const over = live.filter((row) => row.over);
  const json = process.argv.includes('--json');

  if (json) {
    console.log(JSON.stringify({ defaultCapKb: DEFAULT_DOC_KB, rows, over: over.length }, null, 2));
  } else {
    const pad = (value, width) => String(value).padStart(width);
    // Tightest first: the document about to hit its cap is the one worth seeing.
    for (const row of live.sort((a, b) => a.headroomKb - b.headroomKb)) {
      const mark = row.over ? 'OVER' : '    ';
      console.log(
        `${mark} ${pad(row.kb.toFixed(1), 7)} KB  cap ${pad(row.capKb, 3)}  ` +
          `headroom ${pad(row.headroomKb.toFixed(1), 6)}  ${row.file}${row.named ? '' : ' (default)'}`,
      );
    }
    for (const row of rows.filter((item) => item.exempt)) {
      console.log(`     ${pad(row.kb.toFixed(1), 7)} KB  exempt              ${row.file}`);
    }
    console.log(
      `\n${live.length} budgeted documents, ${rows.length - live.length} exempt, ${over.length} over. ` +
        'When one is tight: split it and link the split — never raise the number here.',
    );
  }
  process.exit(over.length ? 1 : 0);
};

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
