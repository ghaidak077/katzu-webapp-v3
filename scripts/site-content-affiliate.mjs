/**
 * `/affiliate` — the partner page, and the two build pieces that make a partner
 * link work in a browser.
 *
 * WHY IT IS SEPARATE FROM `site-content.mjs`
 * The page plus its capture script and config loader are large enough that living
 * in `build-website.mjs` pushed that file past its 500-line budget
 * (`tests/codeBudgets.test.ts`). They are also one subject: the partner programme.
 * Splitting them keeps the build a shell and keeps every number on `/affiliate`
 * read from `AFFILIATE_CONFIG` — the same object `cloudflare-affiliate.js` pays
 * from — instead of being typed into the page.
 */

import { mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

import { PLANS, WORKER, formatUsd } from './site-pricing.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * The partner programme's numbers, from the module the Worker pays from.
 *
 * `/affiliate` states a rate, an approval window, a minimum payout and a list of
 * methods. Typing those into the page would create a second copy of a rule that
 * already exists in `cloudflare-affiliate.js` — the exact drift this build exists
 * to prevent. So the module is bundled and read, like the trust content.
 */
export async function loadAffiliateConfig() {
  const outfile = join(root, 'node_modules', '.cache', `katzu-affiliate-${process.pid}.mjs`);
  mkdirSync(dirname(outfile), { recursive: true });
  await build({
    entryPoints: [join(root, 'cloudflare-affiliate.js')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    outfile,
    logLevel: 'silent',
  });
  const mod = await import(pathToFileURL(outfile).href);
  if (!mod?.AFFILIATE_CONFIG) throw new Error('affiliate config failed to load');
  return mod.AFFILIATE_CONFIG;
}

/**
 * `/assets/ref.js` — the partner link, read in the browser.
 *
 * A partner shares `website.katzuai.com/?ref=CODE` (or the same on the app). The
 * cookie has to live on `.katzuai.com` because the app is on the parent domain
 * and only that cookie crosses the boundary; the app reads it at signup and the
 * Worker validates it there. 30 days, Lax, readable by script.
 *
 * The Worker is asked whether the code exists (`POST /affiliate/ref`, rate
 * limited) so a dead link does not become a 30-day attribution. `text/plain`
 * keeps that request simple — no preflight. If the Worker cannot be reached the
 * cookie stays: an unknown code is dropped at signup anyway, while a missing
 * cookie loses a real partner's commission.
 */
export function affiliateCaptureScript() {
  return `/* Generated by scripts/build-website.mjs. Do not edit. */
(function () {
  var CODE = /^[A-Z0-9]{3,20}$/;
  var raw = "";
  try {
    raw = new URLSearchParams(location.search).get("ref") || "";
  } catch (e) {
    return;
  }
  var code = raw.trim().toUpperCase();
  if (!CODE.test(code)) return;

  var host = location.hostname;
  var onDomain = /(^|\\.)katzuai\\.com$/.test(host);
  var scope = "; path=/" + (onDomain ? "; domain=.katzuai.com" : "");
  var secure = location.protocol === "https:" ? "; secure" : "";
  document.cookie =
    "katzu_ref=" + encodeURIComponent(code) + scope + "; max-age=2592000; samesite=lax" + secure;

  try {
    fetch(${JSON.stringify(WORKER)} + "/affiliate/ref", {
      method: "POST",
      headers: { "Content-Type": "text/plain;charset=UTF-8" },
      body: JSON.stringify({ code: code }),
      credentials: "omit",
    })
      .then(function (res) { return res.json(); })
      .then(function (data) {
        if (data && (data.error === "unknown_code" || data.error === "malformed_code")) {
          document.cookie = "katzu_ref=" + scope + "; max-age=0" + secure;
        }
      })
      .catch(function () {});
  } catch (e) {
    /* no fetch: the cookie alone is still a valid attribution */
  }
})();
`;
}

